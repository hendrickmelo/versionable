{
    /// <summary>A required label.</summary>
    public string Label { get; } = label;

    /// <summary>The nested object, defaulted.</summary>
    public TomlHost Db { get; } = db ?? new TomlHost();

    /// <summary>Metadata, as the generator would emit it.</summary>
    public static VersionableMetadata Metadata { get; } = new()
    {
        ClrType = typeof(TomlHostRoot),
        Name = "TomlHostRoot",
        Version = 1,
        Hash = "aaaaaa",
        Fields =
        [
            TestMetadata.Field<TomlHostRoot>("label", "Label", typeof(string), "str", root => root.Label),
            TestMetadata.Field<TomlHostRoot>(
                "db",
                "Db",
                typeof(TomlHost),
