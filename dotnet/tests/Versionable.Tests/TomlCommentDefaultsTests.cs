{
    /// <summary>The nested object, defaulted and declared first.</summary>
    public TomlHost Db { get; } = db ?? new TomlHost();

    /// <summary>A defaulted scalar, declared after the nested object.</summary>
    public string Name { get; } = name;

    /// <summary>Metadata, as the generator would emit it.</summary>
