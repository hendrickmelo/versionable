/// <summary>
/// Holds a list defaulted to one element, which is the multi-line default case. Python:
/// <c>TomlListRoot</c>.
/// </summary>
internal sealed class TomlListRoot(string label, List<TomlListItem>? items = null) : IVersionableMetadataProvider
{
    /// <summary>A required label.</summary>
    public string Label { get; } = label;

    /// <summary>The list, defaulted to a single default element.</summary>
    public List<TomlListItem> Items { get; } = items ?? [new TomlListItem()];

    /// <summary>Metadata, as the generator would emit it.</summary>
    public static VersionableMetadata Metadata { get; } = new()
    {
        ClrType = typeof(TomlListRoot),
        Name = "TomlListRoot",
        Version = 1,
        Hash = "aaaaaa",
        Fields =
        [
            TestMetadata.Field<TomlListRoot>("label", "Label", typeof(string), "str", root => root.Label),
            TestMetadata.Field<TomlListRoot>(
                "items",
                "Items",
                typeof(List<TomlListItem>),
                "list[TomlListItem]",
                root => root.Items,
