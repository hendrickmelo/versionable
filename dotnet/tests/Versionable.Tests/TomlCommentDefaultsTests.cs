/// <summary>
/// A defaulted nested object declared <em>before</em> a defaulted scalar: the field order that
/// makes a commented section's placement a correctness question rather than a cosmetic one.
/// </summary>
/// <remarks>
/// No Python counterpart. Its suite declares the nested object last in every commentDefaults
/// fixture, which is why an emitter that writes commented blocks inline passes there.
/// </remarks>
